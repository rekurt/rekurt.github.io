export function alternatePath(path: string, locale: Locale): string {
  const withoutRussianPrefix = path.replace(/^\/ru(?=\/|$)/, "") || "/";
  return locale === "ru" ? `/ru${withoutRussianPrefix}`.replace(/\/+/g, "/") : withoutRussianPrefix;
}
